import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const schemaPath = resolve(
  scriptDirectory,
  '../src/entrypoints/sdk/coreSchemas.ts',
)
const outputPath = resolve(
  scriptDirectory,
  '../src/entrypoints/sdk/coreTypes.generated.ts',
)
const source = readFileSync(schemaPath, 'utf8')
const schemaNames = Array.from(
  source.matchAll(/^export const (\w+) = lazySchema\(/gm),
  match => match[1],
)
const placeholderNames = [
  'APIUserMessagePlaceholder',
  'APIAssistantMessagePlaceholder',
  'RawMessageStreamEventPlaceholder',
  'UUIDPlaceholder',
  'NonNullableUsagePlaceholder',
]
const missingPlaceholders = placeholderNames.filter(
  name => !schemaNames.includes(name),
)
const unexpectedNames = schemaNames.filter(
  name => !name.endsWith('Schema') && !placeholderNames.includes(name),
)
if (
  schemaNames.length === 0 ||
  missingPlaceholders.length > 0 ||
  unexpectedNames.length > 0
) {
  throw new Error(
    `Unexpected core schema declarations; missing placeholders: ${missingPlaceholders.join(', ')}; invalid names: ${unexpectedNames.join(', ')}`,
  )
}

const messageSchema = source.match(
  /export const SDKMessageSchema = lazySchema\(\(\) =>([\s\S]*?)\n\)\n\nexport const FastModeStateSchema/,
)
if (!messageSchema) {
  throw new Error('Could not locate the SDKMessageSchema union')
}
const messageTypes = Array.from(
  messageSchema[1].matchAll(/\b(\w+Schema)\(\)/g),
  match => match[1].replace(/Schema$/, ''),
)
if (messageTypes.length === 0) {
  throw new Error('SDKMessageSchema did not contain any member schemas')
}

const typeOverrides = new Map<string, string>([
  [
    'SDKUserMessage',
    `Omit<
  InferSchema<typeof schemas.SDKUserMessageSchema>,
  'message'
> & {
  message: APIUserMessage
}`,
  ],
  [
    'SDKUserMessageReplay',
    `Omit<
  InferSchema<typeof schemas.SDKUserMessageReplaySchema>,
  'message'
> & {
  message: APIUserMessage
}`,
  ],
  [
    'SDKAssistantMessage',
    `Omit<
  InferSchema<typeof schemas.SDKAssistantMessageSchema>,
  'message'
> & {
  message: APIAssistantMessage
}`,
  ],
  [
    'SDKResultSuccess',
    `Omit<
  InferSchema<typeof schemas.SDKResultSuccessSchema>,
  'usage'
> & {
  usage: NonNullableUsage
}`,
  ],
  [
    'SDKResultError',
    `Omit<
  InferSchema<typeof schemas.SDKResultErrorSchema>,
  'usage'
> & {
  usage: NonNullableUsage
}`,
  ],
  [
    'SDKPartialAssistantMessage',
    `Omit<
  InferSchema<typeof schemas.SDKPartialAssistantMessageSchema>,
  'event'
> & {
  event: RawMessageStreamEvent
}`,
  ],
  ['SDKResultMessage', 'SDKResultSuccess | SDKResultError'],
  ['SDKMessage', messageTypes.map(type => `  | ${type}`).join('\n')],
])

const omittedSchemas = new Set(placeholderNames)
const generatedTypes = schemaNames
  .filter(name => name.endsWith('Schema'))
  .filter(name => !omittedSchemas.has(name))
  .map(schemaName => {
    const typeName = schemaName.replace(/Schema$/, '')
    const type = typeOverrides.get(typeName)
    if (typeName === 'SDKMessage') {
      return `export type SDKMessage =\n${type}`
    }
    if (type !== undefined) {
      return `export type ${typeName} = ${type}`
    }
    return `export type ${typeName} = InferSchema<\n  typeof schemas.${schemaName}\n>`
  })
generatedTypes.push('export type UUID = string')

const output = [
  '// Generated from coreSchemas.ts by scripts/generate-sdk-types.ts.',
  '// Do not edit this file directly.',
  'import type {',
  '  BetaMessage,',
  '  BetaMessageParam,',
  '  BetaRawMessageStreamEvent,',
  "} from '@anthropic-ai/sdk/resources/beta/messages/messages.mjs'",
  "import type { z } from 'zod/v4'",
  "import type { NonNullableUsage } from './sdkUtilityTypes.js'",
  "import type * as schemas from './coreSchemas.js'",
  '',
  'type InferSchema<Schema extends () => z.ZodType> = z.infer<',
  '  ReturnType<Schema>',
  '>',
  '',
  'export type APIUserMessage = BetaMessageParam',
  'export type APIAssistantMessage = BetaMessage',
  'export type RawMessageStreamEvent = BetaRawMessageStreamEvent',
  '',
  ...generatedTypes,
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const currentOutput = readFileSync(outputPath, 'utf8')
  if (currentOutput !== output) {
    throw new Error(
      'Generated SDK types are out of date. Run this script without --check to regenerate them.',
    )
  }
} else {
  writeFileSync(outputPath, output)
}
